"""PlatformIO pre-script: generate a secrets header from the root `.env`.

Wi-Fi / API / relay settings are kept out of the source tree in a git-ignored
`.env` file at the repository root. This script runs before compilation and
writes `firmware/include/secrets_generated.h`, which `config.h` includes:

    WIFI_SSID       2.4 GHz Wi-Fi SSID
    WIFI_PASSWORD   Wi-Fi password
    M5IR_API_KEY    HTTP API bearer token
    RELAY_WS_URL    optional Workers relay WebSocket URL
    DEVICE_TOKEN    optional Workers relay device token

The generated header is git-ignored and regenerated on every build, so the
`.env` file stays the single source of truth. Secret values are never printed;
only the configured key names are logged.
"""

import os

Import("env")  # noqa: F821 - provided by PlatformIO/SCons

PROJECT_DIR = env.subst("$PROJECT_DIR").strip()
ROOT_DIR = os.path.dirname(os.path.abspath(PROJECT_DIR))
INCLUDE_DIR = os.path.join(PROJECT_DIR, "include")
GENERATED_HEADER = os.path.join(INCLUDE_DIR, "secrets_generated.h")

ENV_FILES = (
    os.path.join(ROOT_DIR, ".env"),
    os.path.join(PROJECT_DIR, ".env"),
)

# .env key -> C macro name (all are emitted, empty when not configured)
KEY_TO_MACRO = (
    ("WIFI_SSID", "WIFI_SSID"),
    ("WIFI_PASSWORD", "WIFI_PASSWORD"),
    ("M5IR_API_KEY", "M5IR_API_KEY"),
    ("RELAY_WS_URL", "RELAY_WS_URL"),
    ("DEVICE_TOKEN", "DEVICE_TOKEN"),
)


def parse_env_file(path):
    """Parses KEY=VALUE lines. Returns a dict; never raises on malformed lines."""
    values = {}
    try:
        with open(path, "r", encoding="utf-8") as handle:
            lines = handle.readlines()
    except OSError as error:
        print(f"[env] warning: cannot read {path}: {error}")
        return values

    for line_number, raw in enumerate(lines, start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].strip()
        if "=" not in line:
            print(f"[env] warning: {path}:{line_number}: expected KEY=VALUE, skipped")
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        values[key] = value
    return values


def c_string_literal(value):
    """Encodes a value as a C string literal body (without surrounding quotes).

    Handles backslashes, double quotes and non-ASCII (UTF-8 SSIDs) safely.
    """
    escaped = []
    for char in value:
        if char == "\\":
            escaped.append("\\\\")
        elif char == '"':
            escaped.append('\\"')
        elif char == "\n":
            escaped.append("\\n")
        elif char == "\r":
            escaped.append("\\r")
        elif char == "\t":
            escaped.append("\\t")
        else:
            escaped.append(char)
    return "".join(escaped)


def remove_generated_header():
    try:
        os.remove(GENERATED_HEADER)
    except FileNotFoundError:
        pass


def write_generated_header(values):
    lines = [
        "// AUTO-GENERATED by firmware/extra_script.py - DO NOT EDIT.",
        "// Source: .env at the repository root (git-ignored).",
        "#pragma once",
        "",
    ]
    for env_key, macro in KEY_TO_MACRO:
        lines.append(f'#define {macro} "{c_string_literal(values.get(env_key, ""))}"')
    lines.append("")

    os.makedirs(INCLUDE_DIR, exist_ok=True)
    with open(GENERATED_HEADER, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


def main():
    values = {}
    loaded_from = []
    for path in ENV_FILES:
        if os.path.isfile(path):
            values.update(parse_env_file(path))
            loaded_from.append(path)

    if not loaded_from:
        remove_generated_header()
        print("[env] note: no .env file found; Wi-Fi/API/relay stay disabled")
        print("[env] note: copy .env.example to .env and fill it in")
        return

    write_generated_header(values)
    configured = [
        env_key if values.get(env_key) else f"{env_key} (empty)"
        for env_key, _ in KEY_TO_MACRO
        if env_key in values
    ]
    print(f"[env] loaded {', '.join(loaded_from)}")
    print(f"[env] generated {GENERATED_HEADER}")
    print(f"[env] configured: {', '.join(configured) if configured else 'none'}")


main()
